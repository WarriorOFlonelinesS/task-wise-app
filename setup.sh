#!/bin/bash

# Зупиняти скрипт, якщо якась команда завершиться помилкою
set -e

# Кольори для гарного виводу в термінал
GREEN='\033[0m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

echo -e "${BLUE}==================================================${NC}"
echo -e "${BLUE}   TaskWise AI — Автоматичне розгортання та аудит   ${NC}"
echo -e "${BLUE}==================================================${NC}"

# ---------------------------------------------------------------------
# 1. БЕКЕНД (Laravel & Composer)
# ---------------------------------------------------------------------
echo -e "\n${YELLOW}[1/4] Ініціалізація бекенду (Composer)...${NC}"
if [ -d "backend" ]; then
    cd backend
    
    echo "📦 Встановлення PHP залежностей..."
    composer install --no-interaction --prefer-dist
    
    echo "🔒 Запуск аудиту безпеки Composer..."
    # Використовуємо || true, щоб скрипт не падав, якщо знайдуться вразливості низького рівня
    composer audit || echo -e "${RED}⚠ Знайдено зауваження щодо безпеки в PHP пакетах. Перевірте лог вище.${NC}"
    
    cd ..
else
    echo -e "${RED}❌ Помилка: Папку 'backend' не знайдено!${NC}"
    exit 1
fi

# ---------------------------------------------------------------------
# 2. ФРОНТЕНД (React & pnpm)
# ---------------------------------------------------------------------
echo -e "\n${YELLOW}[2/4] Ініціалізація фронтенду (pnpm)...${NC}"
if [ -d "frontend" ]; then
    cd frontend
    
    echo "📦 Встановлення JavaScript залежностей..."
    pnpm install
    
    echo "🔒 Запуск аудиту безпеки pnpm..."
    pnpm audit || echo -e "${RED}⚠ Знайдено зауваження щодо безпеки в npm пакетах. Перевірте лог вище.${NC}"
    
    cd ..
else
    echo -e "${RED}❌ Помилка: Папку 'frontend' не знайдено!${NC}"
    exit 1
fi

# ---------------------------------------------------------------------
# 3. НАЛАШТУВАННЯ ДЕФОЛТНИХ ПРАВ (Для Docker / Linux)
# ---------------------------------------------------------------------
echo -e "\n${YELLOW}[3/4] Конфігурація прав доступу...${NC}"
if [ -d "backend/vendor" ]; then
    chmod -R 755 backend/vendor
    chmod -R 755 backend/storage
    chmod -R 755 backend/bootstrap/cache
    echo "✅ Права для папок Laravel встановлено."
fi

echo -e "\n${GREEN}==================================================${NC}"
echo -e "${GREEN}🎉 Готово! Все встановлено, перевірено та налаштовано.${NC}"
echo -e "${GREEN}Для запуску проєкту використовуйте: ${NC}"
echo -e "👉 Бекенд: cd backend && php artisan serve"
echo -e "👉 Фронтенд: cd frontend && pnpm dev"
echo -e "${GREEN}==================================================${NC}"